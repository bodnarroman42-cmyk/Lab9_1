// sum.cpp
// Файл реалізації функції sum() у просторі імен nsSum

#include <cmath>
#include "dod.h"
#include "sum.h"
#include "var.h"

using namespace std;
using namespace nsDod;
using namespace nsVar;

void nsSum::sum()
{
    // Оголошення локальних змінних на початку функції
    // (додаткові локальні змінні не потрібні, використовуються глобальні змінні з nsVar)

    n = 0;                               // початковий номер доданка
    a = 1.0;                             // перший доданок ряду (n = 0): (-1)^0 * x^0 / 0! = 1
    s = a;                               // початкове значення суми ряду

    // Підсумовуємо наступні доданки, поки модуль чергового доданка більший за точність e
    do
    {
        n++;                             // перехід до наступного номера доданка
        dod();                           // обчислення чергового доданка a
        s += a;                          // додавання поточного доданка до суми
    } while (fabs(a) > e);
}